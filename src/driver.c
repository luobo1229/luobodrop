NTSTATUS DriverEntry(PDRIVER_OBJECT DriverObject, PUNICODE_STRING RegistryPath)
{
    WDF_DRIVER_CONFIG config;

    WDF_DRIVER_CONFIG_INIT(&config, Mt7922DeviceAdd);
#ifdef MT7922_WIFICX
    config.EvtDriverUnload = UnloadStationPacketTrace;
#endif
    const NTSTATUS status = WdfDriverCreate(DriverObject, RegistryPath, WDF_NO_OBJECT_ATTRIBUTES,
        &config, WDF_NO_HANDLE);
#ifdef MT7922_WIFICX
    if (NT_SUCCESS(status)) {
        Mt7922RegisterStationPacketTrace();
    }
#endif
    return status;
}

NTSTATUS Mt7922DeviceAdd(WDFDRIVER Driver, PWDFDEVICE_INIT DeviceInit)
{
#if !defined(MT7922_USER_MODE) && !defined(MT7922_WIFICX)
    DECLARE_CONST_UNICODE_STRING(access, L"D:P(A;;GA;;;SY)(A;;GRGW;;;BA)");
#endif
    WDF_PNPPOWER_EVENT_CALLBACKS callbacks;
    WDF_OBJECT_ATTRIBUTES attributes;
    WDF_IO_QUEUE_CONFIG queueConfig;
    WDFDEVICE device;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(Driver);

#ifdef MT7922_WIFICX
    status = Mt7922WifiConfigureDeviceInit(DeviceInit);
    if (NT_SUCCESS(status)) {
        status = WdfDeviceInitAssignWdmIrpPreprocessCallback(DeviceInit, SharedIoPreprocess,
            IRP_MJ_DEVICE_CONTROL, NULL, 0);
    }
    if (!NT_SUCCESS(status)) {
        return status;
    }
#endif
#ifdef MT7922_USER_MODE
    WdfDeviceInitSetIoType(DeviceInit, WdfDeviceIoBuffered);
#elif !defined(MT7922_WIFICX)
    WdfDeviceInitSetCharacteristics(DeviceInit,
        FILE_DEVICE_SECURE_OPEN | FILE_AUTOGENERATED_DEVICE_NAME, TRUE);
    status = WdfDeviceInitAssignSDDLString(DeviceInit, &access);
    if (!NT_SUCCESS(status)) {
        return status;
    }

#endif
    WDF_PNPPOWER_EVENT_CALLBACKS_INIT(&callbacks);
    callbacks.EvtDevicePrepareHardware = Mt7922PrepareHardware;
    callbacks.EvtDeviceReleaseHardware = Mt7922ReleaseHardware;
    callbacks.EvtDeviceD0Entry = Mt7922D0Entry;
#ifdef MT7922_WIFICX
    callbacks.EvtDeviceD0EntryPostInterruptsEnabled = Mt7922WifiReportCapabilities;
#endif
#ifndef MT7922_USER_MODE
    callbacks.EvtDeviceD0Exit = Mt7922D0Exit;
#endif
    WdfDeviceInitSetPnpPowerEventCallbacks(DeviceInit, &callbacks);
    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, MT7922_CONTEXT);
    status = WdfDeviceCreate(&DeviceInit, &attributes, &device);
    if (!NT_SUCCESS(status)) {
        return status;
    }

#ifndef MT7922_USER_MODE
    WDF_DMA_ENABLER_CONFIG dma;
    MT7922_CONTEXT *context = Mt7922GetContext(device);

    /* MT7922 WFDMA descriptors use 32-bit addresses. */
    WdfDeviceSetAlignmentRequirement(device, PAGE_SIZE - 1);
    WDF_DMA_ENABLER_CONFIG_INIT(&dma, WdfDmaProfileScatterGatherDuplex, PAGE_SIZE);
    context->DmaEnablerStatus = WdfDmaEnablerCreate(device, &dma,
        WDF_NO_OBJECT_ATTRIBUTES, &context->DmaEnabler);
#endif
#ifndef MT7922_USER_MODE
    WDF_OBJECT_ATTRIBUTES lockAttributes;
    WDF_OBJECT_ATTRIBUTES_INIT(&lockAttributes);
    lockAttributes.ParentObject = device;
    status = WdfSpinLockCreate(&lockAttributes, &context->LinkLock);
    if (!NT_SUCCESS(status)) {
        return status;
    }
#ifdef MT7922_WIFICX
    status = NT_SUCCESS(context->DmaEnablerStatus)
        ? Mt7922WifiInitializeDevice(device) : context->DmaEnablerStatus;
    if (!NT_SUCCESS(status)) {
        return status;
    }
    /* Leave WiFiCx's regular I/O dispatch intact. Only our private requests go here. */
    WDF_IO_QUEUE_CONFIG_INIT(&queueConfig, WdfIoQueueDispatchParallel);
    queueConfig.PowerManaged = WdfFalse;
    queueConfig.EvtIoDeviceControl = SharedIoControl;
    WDF_OBJECT_ATTRIBUTES queueAttributes;
    WDF_OBJECT_ATTRIBUTES_INIT(&queueAttributes);
    queueAttributes.ExecutionLevel = WdfExecutionLevelPassive;
    status = WdfIoQueueCreate(device, &queueConfig, &queueAttributes, &context->SharedQueue);
    return NT_SUCCESS(status) ? WdfDeviceCreateDeviceInterface(device, &GUID_DEVINTERFACE_MT7922_SHARED, NULL)
        : status;
#else
    WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(&queueConfig, WdfIoQueueDispatchParallel);
#endif
#else
    WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(&queueConfig, WdfIoQueueDispatchSequential);
#endif
#ifndef MT7922_WIFICX
    queueConfig.PowerManaged = WdfTrue;
    queueConfig.EvtIoDeviceControl = Mt7922DeviceControl;
#ifndef MT7922_USER_MODE
    WDF_OBJECT_ATTRIBUTES queueAttributes;
    WDF_OBJECT_ATTRIBUTES_INIT(&queueAttributes);
    queueAttributes.ExecutionLevel = WdfExecutionLevelPassive;
    status = WdfIoQueueCreate(device, &queueConfig, &queueAttributes, WDF_NO_HANDLE);
#else
    status = WdfIoQueueCreate(device, &queueConfig, WDF_NO_OBJECT_ATTRIBUTES, WDF_NO_HANDLE);
#endif
    if (!NT_SUCCESS(status)) {
        return status;
    }

    return WdfDeviceCreateDeviceInterface(device, &GUID_DEVINTERFACE_MT7922_PROBE, NULL);
#endif
}

static NTSTATUS Mt7922Identify(WDFDEVICE Device, MT7922_PROBE_INFO *Info)
{
#ifdef MT7922_USER_MODE
    static const WCHAR target7922[] = L"PCI\\VEN_14C3&DEV_0616&SUBSYS_E0DF105B&REV_00";
    static const WCHAR target7925[] = L"PCI\\VEN_14C3&DEV_7925&SUBSYS_60001A3B&REV_00";
    WDFMEMORY memory;
    NTSTATUS status = WdfDeviceAllocAndQueryProperty(Device, DevicePropertyHardwareID,
        NonPagedPoolNx, WDF_NO_OBJECT_ATTRIBUTES, &memory);
    if (!NT_SUCCESS(status)) {
        return status;
    }

    size_t size;
    const WCHAR *ids = WdfMemoryGetBuffer(memory, &size);
    const int length7922 = ARRAYSIZE(target7922) - 1;
    const int length7925 = ARRAYSIZE(target7925) - 1;
    BOOL matches7922 = size >= sizeof(target7922) && ids[length7922] == L'\0' &&
        CompareStringOrdinal(ids, length7922, target7922, length7922, TRUE) == CSTR_EQUAL;
    BOOL matches7925 = size >= sizeof(target7925) && ids[length7925] == L'\0' &&
        CompareStringOrdinal(ids, length7925, target7925, length7925, TRUE) == CSTR_EQUAL;
    WdfObjectDelete(memory);
    if (!matches7922 && !matches7925) {
        return STATUS_NO_SUCH_DEVICE;
    }

    Info->VendorId = MT7922_PCI_VENDOR;
    Info->DeviceId = matches7925 ? MT7925_PCI_DEVICE : MT7922_PCI_DEVICE;
    Info->ChipRevision = 0;
#else
    BUS_INTERFACE_STANDARD bus;
    ULONG pciHeader[3];
    NTSTATUS status = WdfFdoQueryForInterface(Device, &GUID_BUS_INTERFACE_STANDARD,
        (PINTERFACE)&bus, sizeof(bus), 1, NULL);
    if (!NT_SUCCESS(status)) {
        return status;
    }

    ULONG bytesRead = bus.GetBusData(bus.Context, PCI_WHICHSPACE_CONFIG,
        pciHeader, 0, sizeof(pciHeader));
    bus.InterfaceDereference(bus.Context);
    if (bytesRead != sizeof(pciHeader)) {
        return STATUS_IO_DEVICE_ERROR;
    }
    ULONG pciId = pciHeader[0];
    const ULONG deviceId = pciId >> 16;
    if ((pciId & 0xffff) != MT7922_PCI_VENDOR ||
        (deviceId != MT7922_PCI_DEVICE && deviceId != MT7925_PCI_DEVICE)) {
        return STATUS_NO_SUCH_DEVICE;
    }

    Info->VendorId = pciId & 0xffff;
    Info->DeviceId = deviceId;
    Info->PciCommand = pciHeader[1] & 0xffff;
    Info->ChipRevision = pciHeader[2] & 0xff;
#endif
    Info->ChipId = Info->DeviceId == MT7925_PCI_DEVICE
        ? MT7925_CHIP_ID : MT7922_CHIP_ID;
    return STATUS_SUCCESS;
}

#ifndef MT7922_USER_MODE
static NTSTATUS Mt7922ProbeDmaBuffer(MT7922_CONTEXT *Context)
{
    const ULONG bufferBytes = 2 * PAGE_SIZE;
    WDFCOMMONBUFFER buffer;
    NTSTATUS status = Context->DmaEnablerStatus;

    if (!NT_SUCCESS(status)) {
        return status;
    }
    status = WdfCommonBufferCreate(Context->DmaEnabler, bufferBytes,
        WDF_NO_OBJECT_ATTRIBUTES, &buffer);
    if (!NT_SUCCESS(status)) {
        return status;
    }

    PVOID virtualAddress = WdfCommonBufferGetAlignedVirtualAddress(buffer);
    PHYSICAL_ADDRESS logicalAddress = WdfCommonBufferGetAlignedLogicalAddress(buffer);
    if (virtualAddress == NULL ||
        (logicalAddress.QuadPart & (PAGE_SIZE - 1)) != 0 ||
        (ULONGLONG)logicalAddress.QuadPart > (ULONGLONG)MAXULONG - (bufferBytes - 1) ||
        WdfCommonBufferGetLength(buffer) < bufferBytes) {
        status = STATUS_DEVICE_CONFIGURATION_ERROR;
    } else {
        RtlZeroMemory(virtualAddress, bufferBytes);
        Context->Info.DmaBufferBytes = bufferBytes;
    }

    WdfObjectDelete(buffer);
    return status;
}
#endif

NTSTATUS Mt7922PrepareHardware(
    WDFDEVICE Device, WDFCMRESLIST ResourcesRaw, WDFCMRESLIST ResourcesTranslated)
{
    MT7922_CONTEXT *context = Mt7922GetContext(Device);
    MT7922_PROBE_INFO *info = &context->Info;
    ULONG index;

    UNREFERENCED_PARAMETER(ResourcesRaw);

    RtlZeroMemory(info, sizeof(*info));
    NTSTATUS status = Mt7922Identify(Device, info);
    if (!NT_SUCCESS(status)) {
        return status;
    }

    info->Version = MT7922_PROBE_VERSION;
    info->RegisterStatus = (ULONG)STATUS_NOT_SUPPORTED;
    info->FirmwareProbeStatus = (ULONG)STATUS_NOT_SUPPORTED;
    info->DmaBufferStatus = (ULONG)STATUS_NOT_SUPPORTED;
    for (index = 0; index < WdfCmResourceListGetCount(ResourcesTranslated); ++index) {
        PCM_PARTIAL_RESOURCE_DESCRIPTOR resource =
            WdfCmResourceListGetDescriptor(ResourcesTranslated, index);

        if (resource == NULL) {
            return STATUS_DEVICE_CONFIGURATION_ERROR;
        }
        switch (resource->Type) {
        case CmResourceTypeMemory:
            const ULONG minimumBarBytes = info->ChipId == MT7925_CHIP_ID
                ? MT7925_BAR0_MIN_BYTES : MT7922_BAR0_MIN_BYTES;
            if (info->MemoryRangeCount == 0 &&
                resource->u.Memory.Length >= minimumBarBytes) {
                PVOID window = NULL;
#ifdef MT7922_USER_MODE
                status = WdfDeviceMapIoSpace(Device, resource->u.Memory.Start,
                    resource->u.Memory.Length, MmNonCached, &window);
#else
                window = MmMapIoSpaceEx(resource->u.Memory.Start,
                    resource->u.Memory.Length, PAGE_READWRITE | PAGE_NOCACHE);
                status = window != NULL ? STATUS_SUCCESS : STATUS_INSUFFICIENT_RESOURCES;
#endif
                info->RegisterStatus = (ULONG)status;
                if (NT_SUCCESS(status)) {
                    context->RegisterWindow = window;
                    context->RegisterWindowBytes = resource->u.Memory.Length;
                    info->RegisterWindowBytes = resource->u.Memory.Length;
                }
            }
            ++info->MemoryRangeCount;
            break;
        case CmResourceTypeMemoryLarge:
            ++info->MemoryRangeCount;
            break;
        case CmResourceTypeInterrupt:
            ++info->InterruptCount;
            break;
        }
    }
#ifndef MT7922_USER_MODE
    info->DmaBufferStatus = (ULONG)Mt7922ProbeDmaBuffer(context);
#endif
#ifdef MT7922_WIFICX
    if (context->RegisterWindow == NULL || info->DmaBufferStatus != (ULONG)STATUS_SUCCESS) {
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    }
    return Mt7922WifiPrepareDevice(Device, context->RegisterWindow, context->DmaEnabler,
        info->ChipId);
#else
    return STATUS_SUCCESS;
#endif
}

NTSTATUS Mt7922ReleaseHardware(WDFDEVICE Device, WDFCMRESLIST ResourcesTranslated)
{
    MT7922_CONTEXT *context = Mt7922GetContext(Device);

    UNREFERENCED_PARAMETER(ResourcesTranslated);

#ifdef MT7922_WIFICX
    Mt7922WifiReleaseDevice(Device);
#endif
#ifndef MT7922_USER_MODE
    if (context->RetainedMcuBuffer != NULL) {
        /* PnP has stopped the PCI device at release-hardware time. */
        WdfObjectDelete(context->RetainedMcuBuffer);
        context->RetainedMcuBuffer = NULL;
    }
#endif
    if (context->RegisterWindow != NULL) {
#ifdef MT7922_USER_MODE
        WdfDeviceUnmapIoSpace(Device, context->RegisterWindow, context->RegisterWindowBytes);
#else
        MmUnmapIoSpace(context->RegisterWindow, context->RegisterWindowBytes);
#endif
        context->RegisterWindow = NULL;
        context->RegisterWindowBytes = 0;
    }
    return STATUS_SUCCESS;
}

