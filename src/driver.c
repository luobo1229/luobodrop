VOID Mt7922DeviceControl(WDFQUEUE Queue, WDFREQUEST Request,
    size_t OutputBufferLength, size_t InputBufferLength, ULONG IoControlCode)
{
    MT7922_PROBE_INFO *output;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(OutputBufferLength);
    UNREFERENCED_PARAMETER(InputBufferLength);

#ifndef MT7922_USER_MODE
    WDFDEVICE device = WdfIoQueueGetDevice(Queue);
    MT7922_CONTEXT *context = Mt7922GetContext(device);
    if (IoControlCode == IOCTL_MT7922_AWDL_LINK_STATUS ||
        IoControlCode == IOCTL_MT7922_AWDL_LINK_EXCHANGE ||
        IoControlCode == IOCTL_MT7922_AWDL_LINK_EXCHANGE_BATCH ||
        IoControlCode == IOCTL_MT7922_AWDL_LINK_EXCHANGE_FAST_ACK ||
        IoControlCode == IOCTL_MT7922_AWDL_LINK_EXCHANGE_ACK54 ||
        IoControlCode == IOCTL_MT7922_AWDL_LINK_STOP) {
        HandleLinkControl(context, Request, IoControlCode, InputBufferLength);
        return;
    }
    const BOOLEAN transmitAwdl = IsAwdlTransmitOperation(IoControlCode);
    const BOOLEAN startLink = IoControlCode == IOCTL_MT7922_AWDL_LINK_START;
    if (startLink && InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_PEER_BYTES &&
        InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_TCP_TARGET_BYTES &&
        InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_LINK_TARGET_BYTES &&
        InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_RECEIVER_TARGET_BYTES &&
        InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_SERVICE_TARGET_BYTES) {
        WdfRequestComplete(Request, STATUS_INVALID_PARAMETER);
        return;
    }
    const BOOLEAN watchPair = IoControlCode == IOCTL_MT7922_AWDL_WATCH_PAIR;
    if (watchPair && InputBufferLength != MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_WATCH_PEER_BYTES) {
        WdfRequestComplete(Request, STATUS_INVALID_PARAMETER);
        return;
    }
    if (startLink || watchPair || (IoControlCode == IOCTL_MT7922_PROBE_MCU && InputBufferLength == 0) ||
        ((IoControlCode == IOCTL_MT7922_BOOT_FIRMWARE ||
        IoControlCode == IOCTL_MT7922_RECEIVE_AWDL || transmitAwdl) &&
        (InputBufferLength == MT7922_FACTORY_IMAGE_BYTES ||
            InputBufferLength == MT7922_REFERENCE_IMAGE_BYTES ||
            (transmitAwdl && (InputBufferLength == MT7922_FACTORY_IMAGE_BYTES + MT7922_AWDL_PEER_BYTES ||
                InputBufferLength == MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_PEER_BYTES ||
                InputBufferLength == MT7922_FACTORY_IMAGE_BYTES + MT7922_AWDL_TCP_TARGET_BYTES ||
                InputBufferLength == MT7922_REFERENCE_IMAGE_BYTES + MT7922_AWDL_TCP_TARGET_BYTES))))) {
        if (InterlockedCompareExchange(&context->McuBusy, 1, 0) != 0) {
            WdfRequestComplete(Request, STATUS_DEVICE_BUSY);
            return;
        }
        HandleMcuProbe(device, Request, IoControlCode);
        InterlockedExchange(&context->McuBusy, 0);
        return;
    }
#endif
    if (IoControlCode != IOCTL_MT7922_PROBE_GET_INFO) {
        WdfRequestComplete(Request, STATUS_INVALID_DEVICE_REQUEST);
        return;
    }

    status = WdfRequestRetrieveOutputBuffer(Request, sizeof(*output), (PVOID *)&output, NULL);
    if (!NT_SUCCESS(status)) {
        WdfRequestComplete(Request, status);
        return;
    }
    *output = Mt7922GetContext(WdfIoQueueGetDevice(Queue))->Info;
    WdfRequestCompleteWithInformation(Request, STATUS_SUCCESS, sizeof(*output));
}
